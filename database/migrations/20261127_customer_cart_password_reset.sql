-- Add cross-device customer carts and secure, one-time customer password reset tokens.
create table if not exists public.customer_carts (
  user_id bigint primary key references public.users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items)='array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_password_resets (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash char(64) not null unique,
  expires_at timestamptz not null,
  used_at timestamptz null,
  created_at timestamptz not null default now()
);
create index if not exists idx_customer_password_resets_user_created
  on public.customer_password_resets (user_id, created_at desc);

drop trigger if exists trg_customer_carts_updated on public.customer_carts;
create trigger trg_customer_carts_updated before update on public.customer_carts
  for each row execute function public.set_updated_at();

alter table public.customer_carts enable row level security;
alter table public.customer_password_resets enable row level security;
revoke all on public.customer_carts from anon, authenticated;
revoke all on public.customer_password_resets from anon, authenticated;
