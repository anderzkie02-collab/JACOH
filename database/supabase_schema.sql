-- keep updated_at fresh (MySQL "ON UPDATE CURRENT_TIMESTAMP" equivalent)
do $$
declare t text;
begin
  foreach t in array array['users','login_attempts','products','customers','customer_carts','orders','inquiries','customer_account_suspensions','product_reviews'] loop
    execute format('drop trigger if exists trg_%1$s_updated on public.%1$s', t);
    execute format('create trigger trg_%1$s_updated before update on public.%1$s for each row execute function public.set_updated_at()', t);
  end loop;
end $$;

-- lock every table away from the public Supabase API
do $$
declare t record;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', t.tablename);
    execute format('revoke all on public.%I from anon, authenticated', t.tablename);
  end loop;
end $$;
