create index if not exists idx_inquiries_seller_status on inquiries (seller_id, status);
create index if not exists idx_inquiries_customer on inquiries (customer_id);
create index if not exists idx_inquiries_responder on inquiries (responded_by);

create table if not exists activity_logs (
