-- JACOH Apparel – PostgreSQL schema for Supabase
-- All tables have Row Level Security ON with no policies: the public Supabase API (anon / authenticated keys)
-- cannot read or write them. Only the Node server, connecting with the database connection string, can.

create or replace function public.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;

create table if not exists users (
  id bigint generated by default as identity primary key,
  email varchar(254) not null unique,
  full_name varchar(120) not null,
  password_hash varchar(100) not null,
  account_type text not null default 'customer' check (account_type in ('owner','seller','customer')),
  active smallint not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_users_type_active on users (account_type, active);

create table if not exists sessions (
  token_hash char(64) primary key,
  user_id bigint not null references users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_sessions_user on sessions (user_id);
create index if not exists idx_sessions_expiry on sessions (expires_at);

create table if not exists customer_password_resets (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  token_hash char(64) not null unique,
  expires_at timestamptz not null,
  used_at timestamptz null,
  created_at timestamptz not null default now()
);
create index if not exists idx_customer_password_resets_user_created on customer_password_resets (user_id, created_at desc);

create table if not exists login_attempts (
  email_hash char(64) primary key,
  attempts integer not null default 0,
  locked_until timestamptz null,
  updated_at timestamptz not null default now()
);

create table if not exists products (
  id varchar(64) primary key,
  seller_id bigint not null references users(id),
  sku varchar(64) not null unique,
  name varchar(160) not null,
  description text not null,
  category varchar(48) not null,
  color varchar(64) not null,
  price integer not null check (price >= 0),
  image varchar(500) not null,
  sizes jsonb not null,
  colors jsonb not null,
  stock integer not null default 0 check (stock >= 0),
  active smallint not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_products_seller_active on products (seller_id, active);
create index if not exists idx_products_category on products (category, active);

create table if not exists customers (
  id bigint generated by default as identity primary key,
  user_id bigint null references users(id) on delete set null,
  email varchar(254) not null unique,
  full_name varchar(120) not null,
  phone varchar(40) not null default '',
  address varchar(255) not null default '',
  city varchar(120) not null default '',
  postal_code varchar(24) not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_customers_user on customers (user_id);

create table if not exists customer_carts (
  user_id bigint primary key references users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items)='array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists orders (
  id varchar(24) primary key,
  customer_id bigint not null references customers(id),
  status text not null default 'to_pack' check (status in ('to_pack','processing','ready_to_ship','completed','cancelled')),
  payment_method text not null default 'cash_on_delivery' check (payment_method in ('cash_on_delivery')),
  subtotal integer not null,
  delivery_fee integer not null,
  total integer not null,
  client_reference varchar(64) null unique,
  request_hash char(64) null,
  delivery_notes varchar(500) not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_orders_status_created on orders (status, created_at);
create index if not exists idx_orders_customer on orders (customer_id);

create table if not exists order_receipt_details (
  order_id varchar(24) primary key references orders(id) on delete cascade,
  customer_name varchar(120) not null,
  customer_email varchar(254) not null,
  customer_phone varchar(40) not null,
  delivery_address varchar(255) not null,
  delivery_city varchar(120) not null,
  delivery_postal_code varchar(24) not null,
  created_at timestamptz not null default now()
);

create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id varchar(24) not null references orders(id) on delete cascade,
  product_id varchar(64) not null references products(id),
  seller_id bigint not null references users(id),
  sku varchar(64) not null,
  item_name varchar(160) not null,
  unit_price integer not null,
  quantity smallint not null,
  selected_size varchar(24) not null,
  selected_color varchar(64) not null
);
create index if not exists idx_order_items_seller on order_items (seller_id, order_id);
create index if not exists idx_order_items_order on order_items (order_id);
create index if not exists idx_order_items_product on order_items (product_id);

create table if not exists stock_movements (
  id bigint generated by default as identity primary key,
  product_id varchar(64) not null references products(id),
  seller_id bigint not null references users(id),
  actor_user_id bigint null references users(id) on delete set null,
  movement_type varchar(32) not null,
  quantity_delta integer not null,
  reference_id varchar(64) not null default '',
  created_at timestamptz not null default now()
);
create index if not exists idx_stock_seller_created on stock_movements (seller_id, created_at);
create index if not exists idx_stock_product on stock_movements (product_id);
create index if not exists idx_stock_actor on stock_movements (actor_user_id);

create table if not exists inquiries (
  id bigint generated by default as identity primary key,
  customer_id bigint null references customers(id) on delete set null,
  seller_id bigint null references users(id) on delete set null,
  customer_name varchar(120) not null,
  customer_email varchar(254) not null,
  subject varchar(180) not null,
  message text not null,
  status text not null default 'open' check (status in ('open','processing','resolved')),
  response text null,
  responded_by bigint null references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
